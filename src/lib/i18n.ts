const STRINGS: Record<Lang, Record<StringKey, string>> = { en, bn };
const BANGLA_DIGITS = "০১২৩৪৫৬৭৮৯";

export function localizeDigits(value: number | string, lang: Lang) {
    const text = String(value);
    return lang === "bn" ? text.replace(/[0-9]/g, (d) => BANGLA_DIGITS[Number(d)]) : text;
}

export function translate(lang: Lang, key: string, params: Record<string, string | number> = {}) {
    const template = STRINGS[lang][key as StringKey] ?? STRINGS.en[key as StringKey] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name: string) => {
        const value = params[name];
        return typeof value === "number" ? localizeDigits(value, lang) : String(value ?? "");
    });
}

export type Translate = (key: StringKey, params?: Record<string, string | number>) => string;
